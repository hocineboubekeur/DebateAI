/**
 * Interpolates placeholder values into translation strings.
 * Usage: formatString(t.profile_level_competitor, 5) → "Level 5 Competitor"
 */
export const formatString = (template, ...args) => {
  if (!template) return '';
  return args.reduce((str, val, i) => str.replace(`{${i}}`, val), template);
};
